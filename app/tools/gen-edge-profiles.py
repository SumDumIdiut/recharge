#!/usr/bin/env python3
"""Writes src/maps/edgeprofiles.js: for each edge piece (family, tile id, role T/B/L/R) of the block sheets, the cleanest
line of pixels across its band (no rivets / brick gaps: the most common row or column) and how thick the band is.
The editor builds an inside-corner connector out of those. Usage: gen-edge-profiles.py need.json > src/maps/edgeprofiles.js
need.json: [[family, edgeId, role, centreId], ...] (the editor's BLOCK_SETS, see tests/amp-tiling.test.mjs)."""
import json, sys, os
from collections import Counter
from PIL import Image
D = os.path.join(os.path.dirname(__file__), '../src/maps/')
art = json.load(open(D + 'basemap.json'))['art']; atlas = Image.open(D + 'tiles.png').convert('RGBA')
def tile(fam, i):
    x, y, w, h = art['sprites'][art['tiles'][fam + str(i)]]
    return atlas.crop((x, y, x + w, y + h))
def close(a, b): return a[3] == b[3] and (a[3] == 0 or sum(abs(p - q) for p, q in zip(a[:3], b[:3])) < 18)
out = {}
for fam, eid, role, cid in json.load(open(sys.argv[1])):
    t, c = tile(fam, eid), tile(fam, cid)
    centre = c.getpixel((16, 16)); W, H = t.size
    vertical = role in 'LR'   # band runs top-bottom; profile is taken across columns at one row
    # candidate lines: the row (vertical bands) / column (horizontal bands) as tuples of pixels from the edge inwards
    def line(n):
        if vertical: return [t.getpixel((W - 1 - d if role == 'R' else d, n)) for d in range(28)]
        return [t.getpixel((n, d if role == 'T' else H - 1 - d)) for d in range(28)]
    n_lines = H if vertical else W
    lines = [tuple(line(n)) for n in range(n_lines)]
    mode, _ = Counter(lines[4:n_lines - 4]).most_common(1)[0]
    idx = next(n for n in range(4, n_lines - 4) if lines[n] == mode)
    thick = 1
    for d, p in enumerate(mode):
        if not close(p, centre): thick = d + 1
    out[f'{fam}|{eid}|{role}'] = [idx, thick]
print('// Generated by tools/gen-edge-profiles.py: "family|edge tile|role" -> [clean line index, band thickness in px]')
print('export const EDGE_PROFILE = ' + json.dumps(out, indent=1) + ';')
